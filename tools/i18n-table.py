def with_joins(idx):
    table = {row[0]: row[idx] for row in EXACT}
    extra = []
    for parts in JOINS:
        extra.append((("".join(parts)), "".join(table[p] for p in parts)))
    return extra


def js(lang, idx):
    exact = {}
    for row in EXACT:
        exact.setdefault(row[0].strip(), row[idx])
    for key, value in with_joins(idx):
        exact.setdefault(key.strip(), value)
    patterns = [[p[0], p[idx]] for p in PATTERNS]
